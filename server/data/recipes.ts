/**
 * 초기 레시피 데이터
 * 저장소가 비어 있을 때(또는 SEED_VERSION이 올라갔을 때) 서버에서 채워 넣는 용도로 사용한다.
 * 사진은 Unsplash(https://unsplash.com/license) 무료 이미지를 원본 주소로 불러온다.
 */

/** 초기 데이터 버전: 레시피를 추가하면 올리고, 추가한 레시피의 since에 같은 값을 적는다 */
export const SEED_VERSION = 2

type IngredientSeed = [name: string, amount: string]

interface RecipeSeed extends Omit<Recipe, 'ingredients' | 'steps' | 'createdAt' | 'updatedAt'> {
  ingredients: IngredientSeed[]
  steps: string[]
  /** 이 레시피가 처음 추가된 초기 데이터 버전 (생략하면 1) */
  since?: number
}

export interface SeedRecipe {
  recipe: Recipe
  since: number
}

const SEEDED_AT = '2026-10-08T00:00:00.000Z'

/** Unsplash 사진을 고화질(가로 1600px)로 불러오는 주소 */
function unsplash(photoId: string): string {
  return `https://images.unsplash.com/${photoId}?auto=format&fit=crop&w=1600&q=80`
}

function toSeedRecipe({ since = 1, ...seed }: RecipeSeed, index: number): SeedRecipe {
  // 목록이 등록 순서(createdAt 오름차순)로 정렬되므로 초기 데이터 순서를 유지하도록 1초씩 차이를 둔다
  const seededAt = new Date(Date.parse(SEEDED_AT) + index * 1000).toISOString()

  return {
    since,
    recipe: {
      ...seed,
      ingredients: seed.ingredients.map(([name, amount], index) => ({
        id: `${seed.id}-ingredient-${index + 1}`,
        name,
        amount,
      })),
      steps: seed.steps.map((description, index) => ({
        id: `${seed.id}-step-${index + 1}`,
        order: index + 1,
        description,
      })),
      createdAt: seededAt,
      updatedAt: seededAt,
    },
  }
}

